    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // Ambil isi username & password dari form
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        // Cek dulu, jangan sampai ada yang kosong
        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Username dan password harus diisi ya.",
                    "Peringatan",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            txtUsername.requestFocus();
            return;
        }

        // Cek akun ke file data (password dibandingkan lewat hash)
        try {
            if (PenyimpananFile.cekLogin(username, password, peran)) {
                // Cocok: buka menu sesuai peran, lalu tutup layar login
                if (PenyimpananFile.PERAN_DOKTER.equals(peran)) {
                    new FormDokter().setVisible(true);
                } else {
                    new FormPasien().setVisible(true);
                }
                dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Username atau password salah. Pastikan juga Anda masuk lewat menu yang sesuai (Pasien/Dokter).",
                        "Login Gagal",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                txtPassword.setText("");
                txtPassword.requestFocus();
            }
        } catch (java.io.IOException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Data akun gagal dibaca. Coba lagi nanti.",
                    "Kesalahan",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

