    private void btnKonfirmasiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKonfirmasiActionPerformed
        // Ambil baris pasien yang dipilih di tabel
        int baris = tblJadwal.getSelectedRow();
        if (baris < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Pilih dulu pasien yang mau dikonfirmasi ya.",
                    "Peringatan",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Kolom ke-5 (index 4) adalah Status
        tblJadwal.setValueAt("Terkonfirmasi", baris, 4);
        // TODO: nanti simpan status konfirmasi ke database
    }//GEN-LAST:event_btnKonfirmasiActionPerformed

